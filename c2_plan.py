"""c2_plan.py —— 第 2 步：分析计划（SAP as code）

为什么把分析计划写成代码而不写成文档？

    因为文档约束不了任何人。跑完数据发现不显著，人会自动"再试一个模型"，
    而且每次都有理由。唯一防得住的办法是：跑之前把要跑什么写死，
    后面所有脚本 import 这份常量，口径只允许改这一处。

    改这一处的时候，git diff 会留下痕迹。这就是约束。

产出：docs/china_分析计划.md（由 self_check() 生成）
"""
from __future__ import annotations

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent
SRC = ROOT / "data" / "raw_china" / "rc_china.csv"
OUT = ROOT / "docs" / "china_分析计划.md"

# ============================================================
# 1. 研究问题（PECO）
# ============================================================
PECO = {
    "P": "2010–2016 年中国 11 城体检成人，基线无糖尿病（FPG<7.0）",
    "E": "体质指数 BMI（连续 + 分类）",
    "C": "正常体重组（按所选切点）",
    "O": "新发糖尿病：末次随访 FPG≥7.0 或自报医生诊断",
}

# 主假设必须只有一个，而且要有方向。
# 不写「探索 BMI 与糖尿病的关系」——那是没假设，最后一定会变成「找到什么算什么」。
HYPOTHESIS = (
    "BMI 越高，新发糖尿病风险越高；"
    "且在中国人群中，风险升高的拐点应低于 WHO 的 25，"
    "中国标准 24 更贴合（因中国人群 BMI 均值仅 23.2，按 WHO 标准有 66% 被判为正常）"
)

# ============================================================
# 2. 变量定义
# ============================================================
OUTCOME = "dm_censor"          # Y：1=新发糖尿病
TIME = "followup_years"        # T：随访年数
EVENT = 1
EXPOSURE = "bmi"               # 主暴露
ID = "pid"
SITE = "site"

# BMI 分类：主分析用中国标准，另两套做敏感性分析。
# 依据：OBJECTIVE 里说了，中国人群分布决定了 WHO 的 30 够不到。
BMI_SCHEMES = {
    "china":   ([0, 18.5, 24.0, 28.0, 100], ["偏瘦", "正常", "超重", "肥胖"]),
    "who":     ([0, 18.5, 25.0, 30.0, 100], ["偏瘦", "正常", "超重", "肥胖"]),
    "asia":    ([0, 18.5, 23.0, 27.5, 100], ["偏瘦", "正常", "超重", "肥胖"]),
}
BMI_SCHEME_MAIN = "china"
BMI_REF = "正常"               # 参照组

# ============================================================
# 3. 纳入排除
# ============================================================
# 原数据已剔除基线糖尿病患者，所以主分析不再重复排除。
# 但仍然要处理录入错误——这是审计里发现的（BMI 与身高体重反算差 >2 的行）。
EXCLUDE = {
    "bmi_range": (10, 60),     # 越界视为录入错误
    "age_range": (18, 110),
}

# ============================================================
# 4. 混杂因素：分三层，每一层都有理由
# ============================================================
# 不是「把能拿到的变量全放进去」。放多了会出两个问题：
#   ① 共线性（tg 和 tc 高度相关）
#   ② 过度调整（基线 FPG 很可能是 BMI → 糖尿病 的中介，调了会低估 BMI 效应）
COVARIATES = {
    # 第一层：人口学。必须调，否则年龄差异会冒充 BMI 效应
    "core": ["age", "gender"],
    # 第二层：设计变量。审计发现 15 个站点发病率 0–2.58%，不调就是把城市差异当 BMI 效应
    "design": ["site"],
    # 第三层：代谢指标。调了更严谨，但可能踩到过度调整
    "metabolic": ["tg", "tc", "sbp", "dbp", "alt"],
    # 明确「不放进主模型」的，以及原因
    "excluded": {
        "fpg": "基线血糖，极可能是 BMI→糖尿病 的中介。放主模型会低估 BMI 效应，只做敏感性分析",
        "smoking": "缺失 71.6%，且是站点级结构性缺失（各站点 4%–99%），主模型放它会砍掉七成样本",
        "drinking": "同 smoking",
        "hdl": "缺失 44.6%",
        "ldl": "缺失 44.1%",
        "ast": "缺失 58.2%",
        "family_history": "是独立危险因素而非混杂（不导致 BMI 差异），主模型不调可避免过拟合，敏感性分析里加",
    },
}

# ============================================================
# 5. 模型序列：从粗到细，每一步都能回答一个问题
# ============================================================
MODELS = {
    "M1": {
        "cov": ["age", "gender"],
        "问": "不调整时，BMI 和糖尿病有没有关联",
    },
    "M2": {
        "cov": ["age", "gender", "site"],
        "问": "扣掉站点差异后还成不成立（主模型）",
    },
    "M3": {
        "cov": ["age", "gender", "site", "tg", "tc", "sbp", "dbp", "alt"],
        "问": "再扣掉代谢指标后，效应衰减多少",
    },
    "M4": {
        "cov": ["age", "gender", "site", "tg", "tc", "sbp", "dbp", "alt", "fpg"],
        "问": "扣掉基线血糖后是否被「吃掉」（敏感性，检验中介效应）",
    },
}
MODEL_MAIN = "M2"

# ============================================================
# 6. 统计方法
# ============================================================
METHOD = {
    "描述": "连续变量用中位数(IQR)（BMI/血脂/肝酶都右偏，不用均值±标准差），分类变量用 n(%)",
    "发病率": "每 1000 人年 = 发病人数 / 累计随访年数 × 1000。不用粗率，因为随访 2–7 年不等",
    "主模型": "Cox 比例风险回归（有随访时间，logistic 会把它浪费成二分类）",
    "站点处理": "site 作为分层变量（strata），避免 15 个哑变量吃掉自由度",
    "剂量反应": "限制性立方样条（RCS），4 节点，检验非线性",
    "交互": "BMI × 年龄组、BMI × 性别，用似然比检验",
    "假设检验": "Schoenfeld 残差检验比例风险假设，p<0.05 则该变量加时间交互项",
}

# ============================================================
# 7. 敏感性分析（跑之前就定好要做哪几条）
# ============================================================
SENSITIVITY = {
    "S1": "排除糖尿病前期（5.6≤fpg<7.0，占 12.4%）—— 这批人发病率 11.03%，是正常组的 16 倍",
    "S2": "只保留随访≥2.5 年的人 —— 排除「早就病了只是没查出来」",
    "S3": "加调 family_history —— 主模型不调它的代价有多大",
    "S4": "换 WHO 25/30 切点 —— 结论是否依赖切点选择",
    "S5": "换亚洲 23/27.5 切点",
    "S6": "结局只认 FPG≥7.0，剔除自报确诊的 751 人 —— 结局定义是否影响结论",
}

# ============================================================
# 8. 预设的解读规则（这一步最能防事后编故事）
# ============================================================
# 写在这里的意思是：结果出来长什么样，就按这个说，不许改口。
INTERPRET = {
    "M1→M2 效应衰减 >20%": "站点构成是重要混杂，必须在报告里说明",
    "M2→M3 效应衰减 >30%": "代谢指标是主要通路，BMI 的直接效应有限",
    "M3→M4 效应接近 0 且 CI 跨 1": "BMI 的作用几乎全经由基线血糖，属于中介而非独立危险因素",
    "RCS 检验非线性 p<0.05": "不报单个线性 HR，改报分段 HR 或切点效应",
    "交互 p<0.05": "分层报告，不报总体合并值",
    "比例风险假设 p<0.05": "该变量加时间交互项，或改用分时段 HR",
}


def self_check() -> None:
    """验证这份计划是可执行的：每个分组都有足够的样本和事件数。"""
    df = pd.read_csv(SRC)
    n = len(df)
    lo, hi = EXCLUDE["bmi_range"]
    bad = ((df["bmi"] < lo) | (df["bmi"] > hi)).sum()

    L: list[str] = []
    add = L.append
    add("# 中国体检队列 · 分析计划（SAP as code）\n")
    add("> 由 `c2_plan.py` 生成。**这是跑数据之前写死的，后续所有脚本 import 这里的常量。**\n")

    add("## 1. 研究问题\n")
    add("| | |")
    add("|---|---|")
    for k, v in PECO.items():
        add(f"| **{k}** | {v} |")
    add("")
    add(f"**主假设（只有一个，且有方向）：** {HYPOTHESIS}\n")

    add("## 2. 变量定义\n")
    add(f"- 结局 Y = `{OUTCOME}`（=1 为新发糖尿病）")
    add(f"- 时间 T = `{TIME}`")
    add(f"- 暴露 = `{EXPOSURE}`（连续，每 +1 kg/m²）")
    add(f"- 分类方案（主分析）= **{BMI_SCHEME_MAIN}**，参照组 = 「{BMI_REF}」\n")

    add("## 3. 纳入排除\n")
    add("原数据已剔除基线糖尿病患者（基线 FPG 最大值 6.99），主分析不再重复排除。")
    add(f"仅处理录入错误：BMI 越界 [{lo}, {hi}] 共 **{int(bad)}** 行，标记为缺失。\n")

    add("## 4. 混杂因素（分三层，每层有理由）\n")
    add("| 层 | 变量 | 为什么放 |")
    add("|---|---|---|")
    add(f"| 核心 | {', '.join(COVARIATES['core'])} | 年龄差异会冒充 BMI 效应 |")
    add(f"| 设计 | {', '.join(COVARIATES['design'])} | 15 个站点发病率 0–2.58% |")
    add(f"| 代谢 | {', '.join(COVARIATES['metabolic'])} | 代谢通路上的共同后果 |")
    add("")
    add("**明确不放主模型的，以及原因：**\n")
    add("| 变量 | 原因 |")
    add("|---|---|")
    for k, v in COVARIATES["excluded"].items():
        add(f"| `{k}` | {v} |")
    add("")

    add("## 5. 模型序列（从粗到细，每一步回答一个问题）\n")
    add("| 模型 | 调整变量 | 回答什么 |")
    add("|---|---|---|")
    for m, cfg in MODELS.items():
        mark = " ← **主模型**" if m == MODEL_MAIN else ""
        add(f"| {m}{mark} | {', '.join(cfg['cov'])} | {cfg['问']} |")
    add("")

    add("## 6. 统计方法\n")
    add("| 环节 | 方法 | 为什么 |")
    add("|---|---|---|")
    for k, v in METHOD.items():
        add(f"| {k} | {v.split('，')[0]} | {'，'.join(v.split('，')[1:]) or '—'} |")
    add("")

    add("## 7. 敏感性分析（跑之前定好）\n")
    for k, v in SENSITIVITY.items():
        add(f"- **{k}**：{v}")
    add("")

    add("## 8. 预设解读规则（防事后编故事）\n")
    add("| 如果观察到 | 就这么说 |")
    add("|---|---|")
    for k, v in INTERPRET.items():
        add(f"| {k} | {v} |")
    add("")

    add("## 9. 计划可执行性校验\n")
    add("每个分组必须有足够的事件数（经验值：每组 ≥10 个事件才不会过拟合）。\n")
    add("| 切点方案 | 分组 | 人数 | 发病数 | 结局率 | 是否够用 |")
    add("|---|---|---|---|---|---|")
    for name, (cuts, labels) in BMI_SCHEMES.items():
        g = pd.cut(df["bmi"], cuts, labels=labels, right=False)
        t = df.groupby(g, observed=False).agg(n=(ID, "size"), inc=(OUTCOME, "sum"))
        for lab, row in t.iterrows():
            ok = "够" if row["inc"] >= 10 else ("勉强" if row["inc"] >= 5 else "**不够**")
            add(f"| {name} | {lab} | {int(row['n']):,} | {int(row['inc']):,} | "
                f"{row['inc'] / row['n'] * 100:.2f}% | {ok} |")
    add("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L), encoding="utf-8")
    print(f"[OK] 分析计划已写入 {OUT}")
    print(f"     样本 {n:,}   BMI 越界 {int(bad)} 行")
    print(f"     主模型 {MODEL_MAIN}: {' + '.join(MODELS[MODEL_MAIN]['cov'])}")
    print(f"     敏感性分析 {len(SENSITIVITY)} 条")


if __name__ == "__main__":
    self_check()
